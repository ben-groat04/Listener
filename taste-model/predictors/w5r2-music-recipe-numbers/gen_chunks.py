"""Generate chunk entry files (each a PREDICTORS dict of grid variants) so each harness run stays small.  python3 gen_chunks.py"""
import json, os
import grid
here = os.path.dirname(os.path.abspath(__file__))
allv = {"default": {}, **grid.OAT, **grid.JOINT}
names = [n for n in allv if n != "default"]; CH = 14
for i in range(0, len(names), CH):
    ns = names[i:i + CH]
    open(f"{here}/chunk_{i // CH}.py", "w").write(f'''"""generated by gen_chunks.py: grid variants {ns[0]} .. {ns[-1]} (default included for pairing)"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import procs, grid
_names = {ns!r}
PREDICTORS = {{"default": procs.variant({{}}), **{{n: procs.variant({{**grid.OAT, **grid.JOINT}}[n]) for n in _names}}}}
''')
print(len(names), "variants,", (len(names) + CH - 1) // CH, "chunks")
